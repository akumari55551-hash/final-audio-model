"""Manifest-backed LFCC recording datasets for training and development.

Each training epoch samples one deterministic pseudo-random window per
recording, so longer recordings do not receive greater sample weight. The
window's LFCCs are generated by the shared preprocessing module. Development
inference visits every window in each recording and aggregates logits per
recording; evaluation manifests are never opened by this module.
"""

from __future__ import annotations

import csv
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import torch
from torch import Tensor
from torch.utils.data import Dataset

from training.audio_preprocessing import PreprocessingConfig, process_audio_file

VALID_SPLITS = {"train", "dev"}
CLASS_NAMES = {0: "bona_fide", 1: "spoof"}


@dataclass(frozen=True)
class Recording:
    file_path: Path
    label: int
    split: str
    source: str
    attack_type: str = ""
    speaker_id: str = ""
    utterance_id: str = ""


def read_manifest_records(manifest_path: Path | str, split: str) -> list[Recording]:
    """Read one requested split from a CSV; reject malformed selected rows.

    Combined manifests are supported: rows for other splits are ignored, and
    no evaluation row is returned to the training pipeline. Separate split
    manifests work identically.
    """
    if split not in VALID_SPLITS:
        raise ValueError(f"Only train/dev manifests may be loaded; got {split!r}")
    path = Path(manifest_path).expanduser().resolve()
    if not path.is_file():
        raise FileNotFoundError(f"{split} manifest not found: {path}")

    records: list[Recording] = []
    with path.open("r", newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        required = {"file_path", "label", "split", "source"}
        missing_columns = required - set(reader.fieldnames or ())
        if missing_columns:
            raise ValueError(f"{path}: missing required columns: {sorted(missing_columns)}")

        for line_number, row in enumerate(reader, start=2):
            row_split = (row.get("split") or "").strip().casefold()
            if row_split != split:
                continue
            raw_path = (row.get("file_path") or "").strip()
            if not raw_path:
                raise ValueError(f"{path}:{line_number}: selected {split} row has empty file_path")
            try:
                label = int(row.get("label", ""))
            except (TypeError, ValueError) as exc:
                raise ValueError(f"{path}:{line_number}: label must be 0 or 1") from exc
            if label not in CLASS_NAMES:
                raise ValueError(f"{path}:{line_number}: label must be 0 or 1, got {label}")

            audio_path = Path(raw_path).expanduser()
            if not audio_path.is_absolute():
                audio_path = (path.parent / audio_path).resolve()
            else:
                audio_path = audio_path.resolve()
            if not audio_path.is_file():
                raise FileNotFoundError(f"{path}:{line_number}: audio file not found: {audio_path}")
            source = (row.get("source") or "").strip()
            if not source:
                raise ValueError(f"{path}:{line_number}: selected row has empty source")
            records.append(
                Recording(
                    file_path=audio_path,
                    label=label,
                    split=split,
                    source=source,
                    attack_type=(row.get("attack_type") or "").strip(),
                    speaker_id=(row.get("speaker_id") or "").strip(),
                    utterance_id=(row.get("utterance_id") or "").strip(),
                )
            )

    if not records:
        raise ValueError(f"No {split!r} recordings found in manifest {path}")
    return records


def class_counts(records: list[Recording]) -> dict[int, int]:
    """Return sample counts for both fixed class IDs, including absent classes."""
    counts = {0: 0, 1: 0}
    for record in records:
        counts[record.label] += 1
    return counts


def stratified_limit(records: list[Recording], per_class: int | None) -> list[Recording]:
    """Deterministically cap each class independently (used by smoke runs)."""
    if per_class is None:
        return records
    if per_class < 1:
        raise ValueError("per_class limit must be positive")
    selected: list[Recording] = []
    counts = {0: 0, 1: 0}
    for record in records:
        if counts[record.label] < per_class:
            selected.append(record)
            counts[record.label] += 1
    return selected


class ManifestAudioDataset(Dataset[tuple[Tensor, Tensor]]):
    """Lazy manifest dataset yielding one fixed-window LFCC tensor per file."""

    def __init__(
        self,
        manifest_path: Path | str,
        split: str,
        preprocessing: PreprocessingConfig,
        *,
        seed: int = 42,
        per_class_limit: int | None = None,
    ) -> None:
        self.split = split
        self.preprocessing = preprocessing
        self.seed = seed
        self.epoch = 0
        self.records = stratified_limit(read_manifest_records(manifest_path, split), per_class_limit)
        if not self.records:
            raise ValueError(f"No recordings remain after limiting {split!r} dataset")

    def __len__(self) -> int:
        return len(self.records)

    def set_epoch(self, epoch: int) -> None:
        """Set epoch for repeatable training-window sampling."""
        if epoch < 0:
            raise ValueError("epoch must be non-negative")
        self.epoch = epoch

    def _features(self, record: Recording) -> np.ndarray:
        _, features = process_audio_file(record.file_path, self.preprocessing)
        if features.ndim != 3 or features.shape[1] != self.preprocessing.features.n_coefficients:
            raise ValueError(f"Unexpected LFCC shape {features.shape} from {record.file_path}")
        return features

    def __getitem__(self, index: int) -> tuple[Tensor, Tensor]:
        record = self.records[index]
        features = self._features(record)
        if self.split == "train":
            # Stable across workers/processes; one window per recording means
            # recording-level rather than duration-level sampling weight.
            window_index = (self.seed + self.epoch * 1_000_003 + index) % features.shape[0]
            selected = features[window_index]
        else:
            # The trainer's validation loop intentionally extracts all windows
            # and aggregates recording logits; this single-item access remains
            # useful for diagnostics and uses the first deterministic window.
            selected = features[0]
        feature_tensor = torch.from_numpy(np.array(selected[None, ...], dtype=np.float32, copy=True))
        label_tensor = torch.tensor(record.label, dtype=torch.long)
        return feature_tensor, label_tensor

    def get_all_windows(self, index: int) -> tuple[Tensor, Tensor]:
        """Return all windows for one recording, for recording-level dev metrics."""
        record = self.records[index]
        features = self._features(record)
        feature_tensor = torch.from_numpy(np.array(features[:, None, ...], dtype=np.float32, copy=True))
        label_tensor = torch.tensor(record.label, dtype=torch.long)
        return feature_tensor, label_tensor
